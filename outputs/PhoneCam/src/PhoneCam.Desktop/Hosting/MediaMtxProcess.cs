using System.Diagnostics;
using System.IO;
using System.Net;
using System.Text;

namespace PhoneCam.Desktop.Hosting;

/// <summary>Runs the bundled MediaMTX as a child process; stdout/stderr go to %LOCALAPPDATA%\PhoneCam\logs\mediamtx.log.</summary>
internal sealed class MediaMtxProcess : IAsyncDisposable
{
    private Process? _process;
    private StreamWriter? _log;
    private bool _stopping;

    public static string LogPath => Path.Combine(AppPaths.Logs, "mediamtx.log");

    /// <summary>Raised on a background thread when MediaMTX exits on its own; argument is the last error line.</summary>
    public event Action<string?>? Exited;

    public string? LastError { get; private set; }

    public void Start(IPAddress address, ServerCertificate certificate)
    {
        if (!File.Exists(AppPaths.MediaMtxExe))
            throw new FileNotFoundException("Brak mediamtx.exe obok aplikacji. Zbuduj projekt ponownie (dotnet build).", AppPaths.MediaMtxExe);

        string configPath = Path.Combine(AppPaths.MediaMtxRuntime, "mediamtx.yml");
        File.WriteAllText(configPath, BuildConfig(address, certificate), new UTF8Encoding(false));

        _log = new StreamWriter(new FileStream(LogPath, FileMode.Create, FileAccess.Write, FileShare.Read)) { AutoFlush = true };
        var startInfo = new ProcessStartInfo(AppPaths.MediaMtxExe)
        {
            UseShellExecute = false,
            CreateNoWindow = true,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            WorkingDirectory = AppPaths.MediaMtxRuntime
        };
        startInfo.ArgumentList.Add(configPath);
        var process = new Process { StartInfo = startInfo, EnableRaisingEvents = true };
        process.OutputDataReceived += (_, e) => OnLine(e.Data);
        process.ErrorDataReceived += (_, e) => OnLine(e.Data);
        process.Exited += (_, _) => { if (!_stopping) Exited?.Invoke(LastError); };
        process.Start();
        ChildProcessJob.Add(process);
        process.BeginOutputReadLine();
        process.BeginErrorReadLine();
        _process = process;
    }

    public bool IsRunning => _process is { HasExited: false };

    private void OnLine(string? line)
    {
        if (line is null) return;
        if (line.Contains(" ERR ", StringComparison.Ordinal))
            LastError = line;
        try { _log?.WriteLine(line); } catch (ObjectDisposedException) { }
    }

    private static string BuildConfig(IPAddress address, ServerCertificate certificate)
    {
        static string Yaml(string path) => path.Replace('\\', '/');
        return $"""
            # Generated by PhoneCam on every start; edit MediaMtxProcess.cs instead.
            logLevel: info
            logDestinations: [stdout]
            api: true
            apiAddress: 127.0.0.1:{Ports.MediaMtxApi}
            metrics: false
            pprof: false
            playback: false
            rtmp: false
            hls: false
            srt: false
            moq: false
            rtsp: true
            rtspAddress: 127.0.0.1:{Ports.Rtsp}
            rtspTransports: [tcp]
            webrtc: true
            webrtcAddress: :{Ports.Whip}
            webrtcEncryption: true
            webrtcServerKey: "{Yaml(certificate.PrivateKeyPemPath)}"
            webrtcServerCert: "{Yaml(certificate.CertificatePemPath)}"
            webrtcAllowOrigins: ['https://{address}:{Ports.PhonePage}']
            webrtcLocalUDPAddress: :{Ports.WebRtcUdp}
            webrtcLocalTCPAddress: ''
            webrtcIPsFromInterfaces: false
            webrtcIPsFromInterfacesList: []
            webrtcIPsFromInterfacesExcludeList: []
            webrtcAdditionalHosts: ['{address}']
            webrtcICEServers2: []
            paths:
              {Slots.Iphone}:
                source: publisher
              {Slots.Android}:
                source: publisher

            """;
    }

    public async ValueTask DisposeAsync()
    {
        _stopping = true;
        if (_process is { } process)
        {
            try
            {
                if (!process.HasExited)
                {
                    process.Kill(entireProcessTree: true);
                    await process.WaitForExitAsync().WaitAsync(TimeSpan.FromSeconds(3));
                }
            }
            catch (Exception ex) when (ex is InvalidOperationException or TimeoutException) { }
            process.Dispose();
            _process = null;
        }
        if (_log is not null) await _log.DisposeAsync();
        _log = null;
    }
}
